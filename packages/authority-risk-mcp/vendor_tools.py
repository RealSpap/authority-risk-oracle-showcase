#!/usr/bin/env python3
"""Pre-build step (NOT named build.py: `python -m build` would run a file called build.py found in the working directory instead of the PyPA build module): copy the repository's own read-only modules into the package, byte for byte, so that the package and the repository can never disagree on what a tool answers.

    python3 vendor_tools.py              # fills src/authority_risk_mcp/_vendor/ from ../../scripts (run before `python -m build`)
    python3 vendor_tools.py --npm        # also copies the Python package into npm/python/ (run before `npm pack`)
    python3 vendor_tools.py --check      # exit 1 if _vendor/ differs from the repository scripts (a test runs this)

The modules are the ones behind scripts/agent_tools.py. `evaluate_rules.py` is NOT copied (it holds the rules engine and the alert senders): the few constants and two functions the others import
from it are cut out of it by name, unchanged, into `_vendor/evaluate_rules.py`.
"""
import ast, os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__)); SCRIPTS = os.path.normpath(os.path.join(HERE, "..", "..", "scripts"))
VENDOR = os.path.join(HERE, "src", "authority_risk_mcp", "_vendor")
MODULES = ("agent_tools", "brief", "compare", "dossier", "find", "risk_by_cause", "badges_req", "watch_location")
FROM_EVALUATE_RULES = ("WATCH_SLUGS", "LABEL", "PENDING_CHAIN", "norm", "lower_keys")


def shim():
    src = open(os.path.join(SCRIPTS, "evaluate_rules.py"), encoding="utf-8").read(); tree = ast.parse(src); lines = src.split("\n"); out = []
    found = set()
    for n in tree.body:
        names = [t.id for t in getattr(n, "targets", []) if isinstance(t, ast.Name)] if isinstance(n, ast.Assign) else ([n.name] if isinstance(n, ast.FunctionDef) else [])
        hit = [x for x in names if x in FROM_EVALUATE_RULES]
        if hit: out.append("\n".join(lines[n.lineno - 1:n.end_lineno])); found.update(hit)
    missing = set(FROM_EVALUATE_RULES) - found
    if missing: sys.exit("build: %s not found in evaluate_rules.py" % sorted(missing))
    return "# Generated by vendor_tools.py: the definitions below are cut, unchanged, from scripts/evaluate_rules.py (the rules engine itself is not part of this package).\n\n" + "\n\n".join(out) + "\n"


def expected():
    files = {m + ".py": open(os.path.join(SCRIPTS, m + ".py"), "rb").read() for m in MODULES}
    files["evaluate_rules.py"] = shim().encode(); files["__init__.py"] = b"# vendored modules of the repository's scripts/ folder, copied by vendor_tools.py\n"
    return files


def main():
    want = expected()
    if "--check" in sys.argv:
        bad = [n for n, b in want.items() if not os.path.exists(os.path.join(VENDOR, n)) or open(os.path.join(VENDOR, n), "rb").read() != b]
        if bad: print("differs from the repository scripts:", ", ".join(sorted(bad))); sys.exit(1)
        print("vendored modules match the repository scripts"); return
    os.makedirs(VENDOR, exist_ok=True)
    for n, b in want.items(): open(os.path.join(VENDOR, n), "wb").write(b)
    print("vendored %d modules" % len(want))
    if "--npm" in sys.argv:
        dest = os.path.join(HERE, "npm", "python", "authority_risk_mcp")
        if os.path.isdir(os.path.join(HERE, "npm", "python")): shutil.rmtree(os.path.join(HERE, "npm", "python"))
        shutil.copytree(os.path.join(HERE, "src", "authority_risk_mcp"), dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        for extra in ("README.md", "LICENSE"): shutil.copy2(os.path.join(HERE, extra), os.path.join(HERE, "npm", extra))
        print("copied the Python package, README.md and LICENSE into npm/")


if __name__ == "__main__":
    main()
